# 9. Leave-one-gene-out
#    sensitivity analysis
############################

Herreros_LOO_cor <- sapply(
  Herreros_genes,
  function(gene_to_remove) {
    
    remaining_genes <- setdiff(
      Herreros_genes,
      gene_to_remove
    )
    
    remaining_score <- colMeans(
      Herreros_expr_z[
        remaining_genes,
        ,
        drop = FALSE
      ],
      na.rm = TRUE
    )
    
    cor(
      Herreros_CSC6_score,
      remaining_score,
      method = "pearson",
      use = "pairwise.complete.obs"
    )
  }
)

